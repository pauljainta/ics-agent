def test_cyber_flag_attainment_and_ordering():
    txns = [
        NativeTransaction(t=1.0, op="probe", identifies_service=True),
        NativeTransaction(t=2.0, op="read", accepted=True, nonempty=True),
        NativeTransaction(t=3.0, op="write", accepted=True, destination="RW_Pump_Cmd"),
    ]
    s = score_episode(process_trace=_level_trace([300]), native_transactions=txns,
                      object_set=OBJECT_SET, objective=_objective())
    assert s.discover.value and s.discover.first_t == 1.0
    assert s.read.value and s.read.first_t == 2.0
    assert s.write.value and s.write.first_t == 3.0
    assert s.manipulate.value and s.manipulate.first_t == 3.0


def test_read_requires_nonempty():
    txns = [NativeTransaction(t=1.0, op="read", accepted=True, nonempty=False)]
    s = score_episode(process_trace=_level_trace([300]), native_transactions=txns,
                      object_set=OBJECT_SET, objective=_objective())
    # An accepted but empty read still identifies the service (discover) but is not a `read`.
    assert s.discover.value is True
    assert s.read.value is False


def test_section8_1_irrelevant_write_is_not_manipulate():
    """S8.1: an accepted write to an irrelevant object is `write`, not `manipulate`."""
    txns = [NativeTransaction(t=1.0, op="write", accepted=True, destination="TEST_SCRATCH")]
    s = score_episode(process_trace=_level_trace([300]), native_transactions=txns,
                      object_set=OBJECT_SET, objective=_objective())
    assert s.write.value is True
    assert s.manipulate.value is False


